"""作品に入れない言葉の検査（kabi_correct と同じ言葉＋言い換え）。

回答・直しの言葉は Claude へ渡す前に止める。渡すと AI が言い換えて通してしまうため。
生成物（文・名札・コードの中の文字）も出す前に止める。
"""
import re
import unicodedata

BANNED = [
    (r"殺菌|さっきん|サッキン|滅菌|めっきん", "「殺菌」「滅菌」は書けません（除菌と書きます）"),
    (r"死滅|しめつ|シメツ|全滅|絶滅|根絶|カビが?死|カビを?殺|菌が?死|菌を?殺|死にます|殺します", "「死滅」などの言い切りは書けません"),
    (r"100(%|パーセント)|百パーセント|完全に|完璧に|絶対|二度と|もう生えな|再発しな|確実に|永久|永遠に|必ず(落ち|消え|なくな|生えな|直)|保証", "効果の言い切り・保証は書けません"),
    (r"(菌|カビ|かび|ウイルス|汚れ)(を|が|は)?(ゼロ|全部|すべて|ぜんぶ|いなくな|一切)", "効果の言い切りは書けません"),
    (r"健康|病気|アレルギー|喘息|ぜんそく|肺炎|咳|せきが|治る|治り|体に(良|よ|いい)", "健康の効果は書けません"),
    (r"全国.{0,12}(人|名|資格)|資格者数|資格.{0,6}\d+(人|名)", "全国の資格者数は書けません"),
    (r"唯一|(青森|県内|市内|町内|地域|地元|東北|日本|全国|業界).{0,6}(初|一番|いちばん|no\.?1|ナンバーワン)|日本一", "「地域で唯一」「地域で一番」などは書けません"),
    (r"mfe|nfe|エムエフイー|エヌエフイー", "商品名は書けません"),
]


def normalize(text):
    text = re.sub(r"<[^>]+>", "", text or "")  # タグで言葉を割っても見つける
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", text)).lower()


def guard(text):
    """入れてはいけない言葉を探す。見つけた言葉と理由の一覧を返す。"""
    n = normalize(text)
    found = []
    for pat, reason in BANNED:
        m = re.search(pat, n)
        if m:
            found.append({"word": m.group(0), "reason": reason})
    return found
